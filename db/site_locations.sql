-- Public booth locations shown on /locations, managed through the
-- "Photoautomat locations" Custom GPT (app/api/gpt/*). Service-role access
-- only: RLS on, no policies. Photos live in the public storage bucket
-- `site-locations`.

create table if not exists public.pb_site_locations (
  id            bigint generated by default as identity primary key,
  name          text        not null,
  address       text        not null,
  lat           double precision not null,
  lng           double precision not null,
  maps_url      text,
  thumb         text,
  status        text        not null default 'draft'
                check (status in ('draft', 'live', 'hidden')),
  sort_order    integer     not null default 0,
  preview_token text        not null default replace(gen_random_uuid()::text, '-', ''),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

alter table public.pb_site_locations enable row level security;

-- This project does not auto-grant new tables to the API roles; only the
-- server (service_role) may touch this table. No delete: hide instead.
grant select, insert, update on table public.pb_site_locations to service_role;
grant usage, select on sequence public.pb_site_locations_id_seq to service_role;

create index if not exists pb_site_locations_status_idx
  on public.pb_site_locations (status, sort_order, id);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('site-locations', 'site-locations', true, 5242880, array['image/jpeg'])
on conflict (id) do nothing;

